/**
 * 第一阶段采用“协议矩阵布局”：x=column、y=row。
 * 这样 UI 看到的顺序与抓包完全一致，空槽则形成自然间隔。
 * 等拿到权威物理尺寸表后，可以新增另一个布局描述器，而不是按键码猜位置。
 */
class C98MatrixLayoutDescriptor implements LayoutDescriptor<MatrixKeyInput> {
  readonly id = 'rk-c98-captured-matrix'

  describe(keys: readonly MatrixKeyInput[]): KeyPosition[] {
    return keys.map((key) => ({
      ...key,
      geometry: { x: key.address.column, y: key.address.row, width: 1, height: 1 },
    }))
  }
}

export const C98_LAYOUT: LayoutDescriptor<MatrixKeyInput> = new C98MatrixLayoutDescriptor()

export const C98_DEMO_KEYS: MatrixKeyInput[] = C98_CAPTURED_DEFAULT_MATRIX.flatMap((row, rowIndex) =>
  row.map((sourceCode, column) => ({
    id: `${rowIndex}-${column}`,
    sourceCode,
    present: sourceCode !== 0,
    label: '',
    address: { kind: 'matrix' as const, row: rowIndex, column },
  })),
)
