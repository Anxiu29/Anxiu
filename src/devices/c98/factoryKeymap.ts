const FACTORY_LAYERS: Readonly<Record<KeyboardMode, readonly (readonly C98FactoryKey[])[]>> = {
  win: [C98_FACTORY_WIN_FN1, C98_FACTORY_WIN_FN2, C98_FACTORY_WIN_FN3, C98_FACTORY_WIN_FN4],
  mac: [C98_FACTORY_MAC_FN1, C98_FACTORY_MAC_FN2, C98_FACTORY_MAC_FN3, C98_FACTORY_MAC_FN4],
}

export function c98FactoryAssignments(mode: KeyboardMode, positions: KeyPosition[], layers: number, keyCatalog: KeyCatalog): KeyAssignment[] {
  return FACTORY_LAYERS[mode].slice(0, layers).flatMap((factoryLayer, layer) => {
    const byPosition = new Map(factoryLayer.map((item) => [item.positionId, item]))
    return positions.map((position) => {
      const factoryKey = byPosition.get(position.id)
      if (!factoryKey) throw new Error(`C98 出厂表缺少键位：${mode} FN${layer + 1} ${position.id}`)
      return { positionId: position.id, sourceCode: position.sourceCode, layer, keyCode: factoryKey.keyCode, category: keyCatalog.get(factoryKey.keyCode).category }
    })
  })
}
