import type { KeyCatalog } from '@/domain/KeyCatalog'
import type { KeyboardMode, KeyAssignment, KeyPosition } from '@/domain/keyboard'

type LayerOverrides = Readonly<Record<number, number>>

/**
 * C98 真机恢复出厂后，通过 0x23 捕获的 WIN/MAC 四层默认映射。
 *
 * 四个配置槽的捕获结果完全一致。FN1 的基础值为物理键码；FN2–FN4
 * 的基础值为固件实际返回的 0x0001。这里只保存与基础值不同的键，既保留
 * 真机数据，也避免把 4 × 2 × 101 条重复记录硬编码八遍。
 */
const FACTORY_OVERRIDES: Readonly<Record<KeyboardMode, readonly LayerOverrides[]>> = {
  win: [
    { 0x01: 0xf001 },
    {
      0x3a: 0x1194, 0x3b: 0x1223, 0x3c: 0x118a, 0x3d: 0x1192, 0x3e: 0x1183,
      0x3f: 0x10b7, 0x40: 0x10b6, 0x41: 0x10cd, 0x42: 0x10b5, 0x43: 0x10e2,
      0x44: 0x10ea, 0x45: 0x10e9, 0x4d: 0x0047, 0x4a: 0x0048, 0x12: 0xf002,
      0x31: 0xf310, 0x04: 0xf101, 0x16: 0xf102, 0x36: 0xf336, 0x52: 0xf312,
      0xe3: 0xf309, 0x2c: 0xf100, 0x50: 0xf315, 0x51: 0xf313, 0x4f: 0xf314,
    },
    { 0x0f: 0xf32d },
    {},
  ],
  mac: [
    { 0xe3: 0x00e2, 0xe2: 0x00e3, 0xe6: 0x00e7, 0x01: 0xf001 },
    {
      0x3a: 0x1070, 0x3b: 0x106f, 0x3c: 0x6152, 0x3d: 0x6807, 0x3e: 0xf313,
      0x3f: 0xf312, 0x40: 0x10b6, 0x41: 0x10cd, 0x42: 0x10b5, 0x43: 0x10e2,
      0x44: 0x10ea, 0x45: 0x10e9, 0x4d: 0x0047, 0x4a: 0x0048, 0x12: 0xf32d,
      0x31: 0xf310, 0x04: 0xf101, 0x16: 0xf102, 0x0f: 0xf32d, 0x36: 0xf336,
      0x52: 0xf312, 0x2c: 0xf100, 0x50: 0xf315, 0x51: 0xf313, 0x4f: 0xf314,
    },
    {},
    {},
  ],
}

export function c98FactoryAssignments(mode: KeyboardMode, positions: KeyPosition[], layers: number, keyCatalog: KeyCatalog): KeyAssignment[] {
  const overrides = FACTORY_OVERRIDES[mode]
  return Array.from({ length: layers }, (_, layer) => positions.map((position) => {
    const baseKeyCode = layer === 0 ? position.sourceCode : 0x0001
    const keyCode = overrides[layer]?.[position.sourceCode] ?? baseKeyCode
    return {
      positionId: position.id,
      sourceCode: position.sourceCode,
      layer,
      keyCode,
      category: keyCatalog.get(keyCode).category,
    }
  })).flat()
}
