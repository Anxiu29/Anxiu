function keyNames(lang: QmkLang) {
  return Object.fromEntries(
    Object.entries(keyNameTable).map(([key, map]) => [key, map[lang] ?? map.en]),
  )
}

function specialTips(lang: QmkLang) {
  return {
    ...Object.fromEntries(
      NAME_KEYS.filter((key) => key !== 'kc_trns' && key !== 'kc_no').map((key) => [
        `tip_${key}`,
        tipTable[key][lang] ?? tipTable[key].en ?? keyNameTable[key][lang] ?? keyNameTable[key].en,
      ]),
    ),
    ...actionTips(lang),
  }
}

