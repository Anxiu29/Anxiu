const actionTipTable: Record<string, LangMap> = Object.fromEntries(
  ACTION_TIP_KEYS.map((key, index) => [key, { cn: cnActionTips[index], tw: twActionTips[index], en: enActionTips[index] }]),
)
for (const [lang, values] of Object.entries(otherActionTips) as Array<[QmkLang, string[]]>) {
  ACTION_TIP_KEYS.forEach((key, index) => { actionTipTable[key][lang] = values[index] })
}

function actionTips(lang: QmkLang) {
  return Object.fromEntries(
    ACTION_TIP_KEYS.map((key) => [`tip_${key}`, actionTipTable[key][lang] ?? actionTipTable[key].en]),
  )
}

function assertLangArrays() {
  const expected = NAME_KEYS.length
  const packs: Array<[string, string[]]> = [
    ['cnNames', cnNames], ['twNames', twNames], ['enNames', enNames],
    ['cnTips', cnTips], ['twTips', twTips], ['enTips', enTips],
    ...Object.entries(otherNames),
    ...Object.entries(otherTips).map(([lang, values]) => [`${lang}Tips`, values] as [string, string[]]),
  ]
  for (const [label, values] of packs) {
    if (values.length !== expected) {
      throw new Error(`QMK i18n ${label} length ${values.length} != ${expected}`)
    }
  }
  const actionExpected = ACTION_TIP_KEYS.length
  const actionPacks: Array<[string, string[]]> = [
    ['cnActionTips', cnActionTips], ['twActionTips', twActionTips], ['enActionTips', enActionTips],
    ...Object.entries(otherActionTips).map(([lang, values]) => [`${lang}ActionTips`, values] as [string, string[]]),
  ]
  for (const [label, values] of actionPacks) {
    if (values.length !== actionExpected) {
      throw new Error(`QMK i18n ${label} length ${values.length} != ${actionExpected}`)
    }
  }
}
assertLangArrays()

